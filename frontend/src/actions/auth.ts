'use server';

import { redirect } from 'next/navigation';
import { createClient, createAdminClient } from '@/lib/supabase/server';
import { revalidatePath } from 'next/cache';
import {
  generateAndStoreKeyForAdmin,
  validateAndConsumeEncryptionKey,
  ADMIN_MASTER_EMAIL,
} from '@/lib/encryption-keys';

/**
 * Login — Email/Password authentication.
 */
export async function login(formData: FormData) {
  const supabase = await createClient();

  const email = (formData.get('email') as string)?.trim().toLowerCase();
  const password = formData.get('password') as string;

  if (!email || !password) {
    return { error: 'Email and password are required.' };
  }

  const { data: authData, error } = await supabase.auth.signInWithPassword({
    email,
    password,
  });

  if (error) {
    console.error('Login failed:', error.message);
    return { error: error.message || 'Authentication failed. Please check your credentials.' };
  }

  if (authData?.user) {
    try {
      const adminSupabase = await createAdminClient();
      const { data: dbUser } = await adminSupabase
        .from('users')
        .select('id, is_active, auth_id, role, name')
        .eq('email', email)
        .single();

      if (dbUser) {
        if (dbUser.is_active === false) {
          await supabase.auth.signOut();
          return { error: 'Your account has been deactivated. Please contact your admin.' };
        }
        if (dbUser.auth_id !== authData.user.id) {
          await adminSupabase
            .from('users')
            .update({ auth_id: authData.user.id })
            .eq('id', dbUser.id);
        }

        // Each login of Admin (Master) automatically generates a new registration encryption key
        if (email === ADMIN_MASTER_EMAIL || dbUser.role === 'admin') {
          try {
            await generateAndStoreKeyForAdmin(adminSupabase, email);
          } catch (keyErr) {
            console.warn('Could not auto-generate login encryption key:', keyErr);
          }
        }
      } else {
        // If user exists in Auth but not in public.users, create their profile row
        await adminSupabase.from('users').insert({
          auth_id: authData.user.id,
          email: authData.user.email || email,
          name: authData.user.user_metadata?.name || email.split('@')[0],
          role: 'admin',
          is_active: true,
        });

        if (email === ADMIN_MASTER_EMAIL) {
          try {
            await generateAndStoreKeyForAdmin(adminSupabase, email);
          } catch (keyErr) {
            console.warn('Could not auto-generate login encryption key:', keyErr);
          }
        }
      }
    } catch (e) {
      console.warn('Could not auto-link user profile:', e);
    }
  }

  revalidatePath('/', 'layout');
  return { success: true };
}

/**
 * Signup — Create account and sign in.
 * Requires a valid Master Encryption Key generated by Admin (Master).
 */
export async function signup(formData: FormData) {
  const supabase = await createClient();
  const adminSupabase = await createAdminClient();

  const name = (formData.get('name') as string)?.trim() || '';
  const email = (formData.get('email') as string)?.trim().toLowerCase();
  const password = formData.get('password') as string;
  const encryptionKey = (formData.get('encryptionKey') as string)?.trim().toUpperCase();

  if (!name || name.length < 2) {
    return { error: 'Full Name is required (minimum 2 characters).' };
  }

  if (!email || !password) {
    return { error: 'Email and password are required.' };
  }

  if (!encryptionKey) {
    return {
      error: 'Master Encryption Key is required. Please obtain the encryption key from Admin (Master) to create your account.',
    };
  }

  if (password.length < 8) {
    return { error: 'Password must be at least 8 characters.' };
  }

  // Password complexity check
  if (!/[A-Z]/.test(password) || !/[0-9]/.test(password)) {
    return { error: 'Password must contain at least one uppercase letter and one number.' };
  }

  // 1. Verify and consume the Master Encryption Key
  try {
    const keyResult = await validateAndConsumeEncryptionKey(adminSupabase, encryptionKey, email);
    if (!keyResult.valid) {
      return { error: keyResult.error || 'Invalid or expired Master Encryption Key.' };
    }
  } catch (keyErr: any) {
    console.error('Key verification error:', keyErr);
    return { error: 'Failed to verify Master Encryption Key: ' + (keyErr.message || 'Key invalid') };
  }

  // 2. Check if user already exists
  try {
    const { data: existingUser } = await adminSupabase
      .from('users')
      .select('id, is_active, auth_id, name')
      .eq('email', email)
      .maybeSingle();

    if (existingUser?.auth_id) {
      return {
        error: `An account for "${email}" already exists. Please return to the login screen to sign in directly with your email and password.`,
      };
    }

    // 3. Pre-insert or update in public.users allow-list so DB trigger links seamlessly
    let publicUserId = existingUser?.id;
    if (!existingUser) {
      const { data: newPubUser, error: pubErr } = await adminSupabase
        .from('users')
        .insert({
          email,
          name,
          role: 'client_manager',
          is_active: true,
          auth_id: null,
          avatar_url: null,
        })
        .select('id')
        .single();

      if (pubErr) {
        console.error('Failed to pre-insert public.users allow-list:', pubErr);
        return { error: 'Failed to create user record: ' + pubErr.message };
      }
      publicUserId = newPubUser.id;
    } else {
      await adminSupabase
        .from('users')
        .update({ name: name || existingUser.name, is_active: true })
        .eq('id', existingUser.id);
    }

    // 4. Create user in Supabase Auth with email pre-confirmed
    const { data: newAuthData, error: authErr } = await adminSupabase.auth.admin.createUser({
      email,
      password,
      email_confirm: true,
      user_metadata: { name, email_verified: true },
    });

    if (authErr) {
      console.error('Auth user creation error:', authErr);
      return { error: 'Account creation failed: ' + authErr.message };
    }

    const authUserId = newAuthData.user.id;

    // 5. Ensure public.users auth_id is linked
    if (publicUserId) {
      await adminSupabase
        .from('users')
        .update({ auth_id: authUserId, is_active: true })
        .eq('id', publicUserId);
    }

    // 6. Sign in the new user immediately to establish browser session
    const { error: loginError } = await supabase.auth.signInWithPassword({
      email,
      password,
    });

    if (loginError) {
      console.error('Post-signup login failed:', loginError);
      return { error: 'Account created successfully! Please click "Back to Login" to sign in.' };
    }
  } catch (err: any) {
    console.error('Unexpected signup error:', err);
    return { error: 'Something went wrong creating your account: ' + (err.message || 'Unknown error') };
  }

  revalidatePath('/', 'layout');
  return { success: true };
}

/**
 * Logout — Sign out and redirect to login page.
 */
export async function logout() {
  const supabase = await createClient();
  await supabase.auth.signOut();
  revalidatePath('/', 'layout');
  redirect('/login');
}

/**
 * Get the currently authenticated user's profile from the users table.
 * Returns null if not authenticated.
 */
export async function getCurrentUser() {
  const supabase = await createClient();

  const { data: { user: authUser } } = await supabase.auth.getUser();
  if (!authUser) return null;

  let { data: dbUser } = await supabase
    .from('users')
    .select('*')
    .eq('auth_id', authUser.id)
    .single();

  if (!dbUser && authUser.email) {
    const { data: userByEmail } = await supabase
      .from('users')
      .select('*')
      .eq('email', authUser.email)
      .single();
    dbUser = userByEmail;
  }

  return dbUser;
}

/**
 * Admin Update Password — Allows an admin to update password for any user or admin.
 */
export async function adminUpdatePassword(formData: FormData) {
  const adminEmail = (formData.get('adminEmail') as string)?.trim().toLowerCase();
  const adminPassword = formData.get('adminPassword') as string;
  const targetEmail = (formData.get('targetEmail') as string)?.trim().toLowerCase();
  const newPassword = formData.get('newPassword') as string;
  const confirmPassword = formData.get('confirmPassword') as string;

  if (!adminEmail || !adminPassword) {
    return { error: 'Admin email and admin password are required for authorization.' };
  }

  if (!targetEmail || !newPassword) {
    return { error: 'Target user email and new password are required.' };
  }

  if (newPassword.length < 8) {
    return { error: 'New password must be at least 8 characters.' };
  }

  if (confirmPassword && newPassword !== confirmPassword) {
    return { error: 'New password and confirmation do not match.' };
  }

  // 1. Verify admin credentials
  const supabase = await createClient();
  const { data: authData, error: authError } = await supabase.auth.signInWithPassword({
    email: adminEmail,
    password: adminPassword,
  });

  if (authError || !authData.user) {
    return { error: 'Invalid admin credentials. Please verify your admin email and password.' };
  }

  // 2. Verify admin role in public.users
  const adminSupabase = await createAdminClient();
  const { data: adminProfile } = await adminSupabase
    .from('users')
    .select('id, role, is_active')
    .or(`auth_id.eq.${authData.user.id},email.eq.${adminEmail}`)
    .single();

  if (!adminProfile || adminProfile.role !== 'admin' || adminProfile.is_active === false) {
    await supabase.auth.signOut();
    return { error: 'Unauthorized: Only active administrators can update passwords.' };
  }

  // 3. Find the target user in Supabase Auth
  const { data: targetProfile } = await adminSupabase
    .from('users')
    .select('id, auth_id, email, name')
    .eq('email', targetEmail)
    .single();

  let targetAuthId = targetProfile?.auth_id;

  if (!targetAuthId) {
    const { data: authUsersList, error: listError } = await adminSupabase.auth.admin.listUsers();
    if (listError) {
      return { error: 'Failed to look up user in authentication directory.' };
    }
    const foundAuthUser = authUsersList.users.find(
      (u) => u.email?.toLowerCase() === targetEmail
    );
    if (foundAuthUser) {
      targetAuthId = foundAuthUser.id;
    }
  }

  if (!targetAuthId) {
    return { error: `No account found for "${targetEmail}".` };
  }

  // 4. Update the target user's password
  const { error: updateError } = await adminSupabase.auth.admin.updateUserById(
    targetAuthId,
    {
      password: newPassword,
      email_confirm: true,
    }
  );

  if (updateError) {
    console.error('Admin password update error:', updateError);
    return { error: `Failed to update password: ${updateError.message}` };
  }

  // Sign out the verification session so user is back on clean login state
  await supabase.auth.signOut();

  return {
    success: true,
    message: `Password updated successfully for ${targetEmail}. You can now sign in with your new password.`,
  };
}
